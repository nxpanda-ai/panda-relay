"""Generates schema/auth-vectors.json — an independent (third) implementation of spec §58 / §71.3.

Run: python schema/auth-vectors.py
The C# (bridge) and TypeScript (extension) auth primitives must both reproduce every vector.
"""
import base64
import hashlib
import hmac
import json
import pathlib
import struct

OUT = pathlib.Path(__file__).with_name("auth-vectors.json")


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).decode().rstrip("=")


def frame(*fields: bytes) -> bytes:
    return b"".join(struct.pack(">I", len(f)) + f for f in fields)


def proof(key: bytes, label: str, *fields: bytes) -> str:
    return hmac.new(key, frame(label.encode("ascii"), *fields), hashlib.sha256).hexdigest()


def normalize(code: str):
    # ASCII-only uppercase: str.upper() would map 'ı' → 'I' and 'ſ' → 'S' (spec §71.3).
    n = "".join(chr(ord(c) - 32) if "a" <= c <= "z" else c for c in code).replace(" ", "").replace("-", "")
    ok = len(n) == 26 and all(c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567" for c in n)
    return n if ok else None


def base32(b: bytes) -> str:
    return base64.b32encode(b).decode().rstrip("=")


def fingerprint(bridge_id: str) -> str:
    h = hashlib.sha256(bridge_id.encode("utf-8")).hexdigest().upper()[:8]
    return f"{h[:4]}-{h[4:]}"


secret = bytes(range(32))
secret2 = bytes(range(255, 223, -1))
ext_nonce = bytes(range(16))
bridge_nonce = bytes(range(16, 32))
code = base32(bytes(range(100, 116)))
browser_ids = ["chrome-abcd2345", "coccoc-k3m7q2xa"]

vectors = {
    "description": "Shared auth test vectors (spec §58, §71.3). Generated by schema/auth-vectors.py — do not edit.",
    "frame": [
        {"fieldsHex": [], "frameHex": ""},
        {"fieldsHex": [""], "frameHex": frame(b"").hex()},
        {"fieldsHex": ["616263", "00ff"], "frameHex": frame(b"abc", b"\x00\xff").hex()},
        # length prefix makes ("ab","c") and ("a","bc") differ
        {"fieldsHex": ["6162", "63"], "frameHex": frame(b"ab", b"c").hex()},
        {"fieldsHex": ["61", "6263"], "frameHex": frame(b"a", b"bc").hex()},
        # 300-byte field pins every byte of the 32-bit big-endian length prefix (00 00 01 2c)
        {"fieldsHex": ["ab" * 300, "01"], "frameHex": frame(b"\xab" * 300, b"\x01").hex()},
    ],
    "base32": [
        {"bytesHex": bytes(range(100, 116)).hex(), "code": code},
        {"bytesHex": "00" * 16, "code": base32(b"\x00" * 16)},
        {"bytesHex": "ff" * 16, "code": base32(b"\xff" * 16)},
    ],
    "normalize": [
        {"input": code, "normalized": code},
        {"input": code.lower(), "normalized": code},
        {"input": "-".join(code[i:i + 4] for i in range(0, 26, 4)), "normalized": code},
        {"input": " " + " ".join(code[i:i + 5] for i in range(0, 26, 5)) + " ", "normalized": code},
        {"input": code[:-1], "normalized": None},
        {"input": code + "A", "normalized": None},
        {"input": code[:-1] + "1", "normalized": None},
        {"input": code[:-1] + "0", "normalized": None},
        {"input": code[:-1] + "É", "normalized": None},
        # non-ASCII letters whose Unicode uppercase is ASCII must still be rejected
        {"input": code[:-1].lower() + "ı", "normalized": None},
        {"input": code[:-1].lower() + "ſ", "normalized": None},
        {"input": code[:-1] + "Ａ", "normalized": None},
        {"input": code[:13] + "\t" + code[13:], "normalized": None},
        {"input": code[:13] + "\u00a0" + code[13:], "normalized": None},
        {"input": "", "normalized": None},
    ],
    "base64url": [
        {"text": b64u(ext_nonce), "length": 16, "bytesHex": ext_nonce.hex()},
        {"text": b64u(secret), "length": 32, "bytesHex": secret.hex()},
        {"text": b64u(ext_nonce) + "==", "length": 16, "bytesHex": None},
        {"text": b64u(ext_nonce)[:-1], "length": 16, "bytesHex": None},
        {"text": b64u(ext_nonce), "length": 32, "bytesHex": None},
        {"text": base64.b64encode(bytes([251] * 16)).decode().rstrip("="), "length": 16, "bytesHex": None},
        {"text": "", "length": 16, "bytesHex": None},
        # last char carries 2 unused bits that must be zero (canonical encoding only)
        {"text": b64u(ext_nonce)[:-1] + "x", "length": 16, "bytesHex": None},
    ],
    "proofs": [],
    "verifyNegative": [],
    "fingerprint": [
        {"bridgeId": "bridge-7f82", "fingerprint": fingerprint("bridge-7f82")},
        {"bridgeId": "cầu-nối", "fingerprint": fingerprint("cầu-nối")},
    ],
}

for bid in browser_ids:
    bidb = bid.encode("utf-8")
    for key in (secret, secret2):
        vectors["proofs"].append({"label": "bridge", "secret": b64u(key), "extNonce": b64u(ext_nonce),
                                  "bridgeNonce": b64u(bridge_nonce), "browserInstanceId": bid,
                                  "proof": proof(key, "bridge", ext_nonce, bridge_nonce, bidb)})
        vectors["proofs"].append({"label": "ext", "secret": b64u(key), "extNonce": b64u(ext_nonce),
                                  "bridgeNonce": b64u(bridge_nonce), "browserInstanceId": bid,
                                  "proof": proof(key, "ext", bridge_nonce, ext_nonce, bidb)})
for c in (code, base32(b"\x00" * 16)):
    vectors["proofs"].append({"label": "pair-bridge", "code": c, "extNonce": b64u(ext_nonce),
                              "bridgeNonce": b64u(bridge_nonce),
                              "proof": proof(c.encode("ascii"), "pair-bridge", ext_nonce, bridge_nonce)})
    vectors["proofs"].append({"label": "pair-ext", "code": c, "extNonce": b64u(ext_nonce),
                              "bridgeNonce": b64u(bridge_nonce),
                              "proof": proof(c.encode("ascii"), "pair-ext", bridge_nonce, ext_nonce)})

good = vectors["proofs"][0]
flipped = good["proof"][:10] + ("0" if good["proof"][10] != "0" else "1") + good["proof"][11:]
for why, received in [("uppercase hex", good["proof"].upper()), ("one hex digit changed", flipped),
                      ("truncated", good["proof"][:-2]), ("extended", good["proof"] + "00"), ("empty", ""),
                      ("non-hex", "z" * 64),
                      ("proof of the other direction", vectors["proofs"][1]["proof"])]:
    vectors["verifyNegative"].append({**{k: v for k, v in good.items() if k != "proof"},
                                      "received": received, "why": why})

OUT.write_text(json.dumps(vectors, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(vectors['proofs'])} proofs)")
